// Default language detection
function detectLanguage() {
  // Check localStorage first
  const stored = localStorage.getItem("chrome_green_lang");
  if (stored === "en" || stored === "zh-CN") return stored;
  if (stored === "auto" || !stored) {
    const nav = navigator.language || "";
    if (nav.startsWith("zh")) return "zh-CN";
    return "en";
  }
  return "en";
}

const locale = reactive({
  current: detectLanguage(),
});

export function t(key) {
  let lang = locale.current;
  const map = translations[lang] || translations["en"];
  const parts = key.split(".");
  let result = map;
  for (const p of parts) {
    if (result && typeof result === "object") {
      result = result[p];
    } else {
      return key;
    }
  }
  return typeof result === "string" ? result : key;
}

export function setLocale(lang) {
  locale.current = lang;
  if (lang === "auto") {
    const nav = navigator.language || "";
    locale.current = nav.startsWith("zh") ? "zh-CN" : "en";
    localStorage.setItem("chrome_green_lang", "auto");
  } else {
    localStorage.setItem("chrome_green_lang", lang);
  }
}

export function getLocale() {
  return locale.current;
}

export { locale };
